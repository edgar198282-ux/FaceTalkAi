const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('web/index.html','utf8');
const start=html.indexOf('function recoverPlaylistLogos(');
const end=html.indexOf('async function load(){',start);
const context=vm.createContext({});
vm.runInContext(html.slice(start,end),context);
const recover=context.recoverPlaylistLogos;
const channel={id:'edo1',name:'Россия 1 UHD',group:'новости',url:'https://stream.example/1',epg_now:{title:'Provider guide'},personal:true};
const known=[{name:'Россия 1 HD',logo:'https://logos.example/r1.png',epg_now:{title:'Other guide'}}];
const [filled]=recover([channel],known);
assert.equal(filled.logo,known[0].logo);
assert.equal(filled.epg_now,channel.epg_now);
assert.equal(filled.url,channel.url);
assert.equal(channel.logo,undefined);
const [original]=recover([{...channel,logo:'https://provider.example/r1.png'}],known);
assert.equal(original.logo,'https://provider.example/r1.png');
assert.equal(original.logo_fallback,known[0].logo);
const [ambiguous]=recover([channel],[...known,{name:'Россия 1',logo:'https://other.example/r1.png'}]);
assert.equal(ambiguous.logo,undefined);
const [unrelated]=recover([{name:'Россия 24',personal:true}],known);
assert.equal(unrelated.logo,undefined);
console.log('Logo recovery: cache/catalogue, provider priority, ambiguity and EPG isolation passed');
